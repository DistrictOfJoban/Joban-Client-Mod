#!/usr/bin/env python3
"""js2cpp.py — a semi-automatic JCM JavaScript → C++ script converter.

Migrating a PIDS/vehicle script from the JS (Rhino) pipeline to the
native pipeline is mostly mechanical: the wrapper API maps nearly
one-to-one, only the call shapes differ (method naming, builder style,
the wrapper object living inside the render() arguments instead of in a
closure). This tool performs the mechanical part and COMMENTS the parts
it cannot decide, so a human finishes the port in minutes instead of
hours.

Usage:
    python3 js2cpp.py input.js -o output.cpp [--id mypack:script]
    python3 js2cpp.py input.js            # prints to stdout

What it does (see docs/js-to-cpp.md for the full mapping table):
  * function create/render/dispose(ctx, state, pids)  ->
      struct State { ... }; struct Script : mtr::PidsScript<State> { ... }
  * pids.arrivals().forEach(...)      ->  for (int i = 0; i < ...) loops
  * new Text(...).draw() / TextWrapper chains -> mtr::Text::create() chains
  * pids.width / pids.height()        ->  pids.width() / pids.height()
  * JS truthiness and var             ->  C++ types kept simple
  * MinecraftClient / GraphicsTexture / SoundManager calls are left as
    TODO comments (they need the api.hpp / gfx.hpp surfaces).

What it deliberately does NOT do:
  * No type inference beyond the obvious — runtime-typed values become
    `/* TODO type */ double` placeholders.
  * No closure state capture — the tool lists captured variables as a
    comment block for the State struct.
  * Eval-anything else is passed through inside a comment for manual
    review.

The output is a starting point, not a finished port. The header include
list is pre-wired for PIDS scripts; delete what you don't use.
"""
import argparse
import re
import sys

HEADER = """// Generated by js2cpp.py (semi-automatic) — review the TODO markers.
// Mapping reference: the SDK's docs/js-to-cpp.md.
#include <mtr/script.hpp>
#include <mtr/gfx.hpp>
#include <mtr/gfx2d.hpp>
#include <cmath>
#include <string>
"""

TEXT_CHAIN = [
    # JS TextWrapper builder methods -> mtr::Text methods (verbatim names).
    ("stretchXY", "stretch_xy"), ("scaleXY", "scale_xy"),
    ("wrapText", "wrap_text"), ("marquee", "marquee"),
    ("centerAlign", "center_align"), ("leftAlign", "left_align"),
    ("rightAlign", "right_align"), ("shadowed", "shadowed"),
    ("bold", "bold"), ("italic", "italic"),
    ("naturalLight", "natural_light"),
]

PROP_TO_METHOD = [
    # JS property accesses -> C++ getter calls on the wrappers.
    (r"\bpids\.width\b", "pids.width()"),
    (r"\bpids\.height\b", "pids.height()"),
    (r"\bvehicle\.speedKmh\b", "vehicle.speed_kmh()"),
    (r"\bvehicle\.speed\b", "vehicle.speed_ms()"),
    (r"\bvehicle\.doorValue\b", "vehicle.door_value()"),
    (r"\bvehicle\.carCount\b", "vehicle.car_count()"),
    (r"\bvehicle\.reversed\b", "vehicle.is_reversed()"),
    (r"\bvehicle\.onRoute\b", "vehicle.on_route()"),
    (r"\bvehicle\.weather\b", "vehicle.getWeather()"),
    (r"\bvehicle\.isExpressService\b", "vehicle.isExpressService()"),
    (r"\bvehicle\.signalState\b", "vehicle.signalState()"),
]

HELPER_REWRITES = [
    # JS global helpers -> C++ equivalents (commented where no direct twin).
    (r"console\.log\(", "/* console.log -> */ std::printf("),
    (r"Math\.floor\(", "std::floor("),
    (r"Math\.ceil\(", "std::ceil("),
    (r"Math\.abs\(", "std::abs("),
    (r"Math\.min\(", "std::min("),
    (r"Math\.max\(", "std::max("),
    (r"Math\.PI\b", "M_PI"),
    (r"Math\.random\(\)", "0.5 /* TODO: Math.random has no twin; precompute or use game_time_millis */"),
    (r"MinecraftClient\.isRiding\(\)", "/* TODO api: MinecraftClientWrapper riding check (api.hpp) */ false"),
    (r"Timing\.now\(\)", "pids.game_time_millis()"),
]

ARRIVAL_FOREACH = re.compile(
    r"pids\.arrivals\(\)\.forEach\(\(arrival\)\s*=>\s*\{")

STATE_HINT = re.compile(
    r"(?:var|let|const)\s+([A-Za-z_$][\w$]*)\s*=\s*([^;]+);")


def convert_forEach(source: str) -> str:
    """pids.arrivals().forEach((arrival) => { ... }) -> index loop."""
    out = []
    pos = 0
    while True:
        match = ARRIVAL_FOREACH.search(source, pos)
        if match is None:
            out.append(source[pos:])
            break
        out.append(source[pos:match.start()])
        body_start = match.end() - 1
        depth = 0
        end = body_start
        for i in range(body_start, len(source)):
            if source[i] == '{':
                depth += 1
            elif source[i] == '}':
                depth -= 1
                if depth == 0:
                    end = i
                    break
        body = source[body_start + 1:end]
        body = body.replace("arrival.", "arrival_.")
        # Map the common ArrivalWrapper property accesses.
        for js, cpp in [
            ("arrival_.arrivalTime()", "arrival_.arrival_time()"),
            ("arrival_.departureTime()", "arrival_.departure_time()"),
            ("arrival_.destination", "arrival_.destination()"),
            ("arrival_.routeName", "arrival_.route_name()"),
            ("arrival_.routeNumber", "arrival_.route_number()"),
            ("arrival_.routeColor", "arrival_.route_color()"),
            ("arrival_.carCount", "arrival_.car_count()"),
            ("arrival_.realtime", "arrival_.realtime()"),
            ("arrival_.terminating", "arrival_.terminating()"),
            ("arrival_.isExpress", "arrival_.isExpress()"),
            ("arrival_.isHiddenRoute", "arrival_.isHiddenRoute()"),
        ]:
            body = body.replace(js, cpp)
        # Consume the forEach call's trailing ");" right after the body.
        pos = end + 1
        while pos < len(source) and source[pos] in " \t\r\n":
            pos += 1
        if pos < len(source) and source[pos] == ')':
            pos += 1
            if pos < len(source) and source[pos] == ';':
                pos += 1
        out.append(
            "auto arrivals_ = pids.arrivals();\n"
            "        for (int i_ = 0; i_ < arrivals_.size(); i_++) {\n"
            "            auto arrival_ = arrivals_.at(i_);\n" + body + "\n        }")
    return "".join(out)


def convert_text_chains(source: str) -> str:
    """new Text("...") ... .draw() -> mtr::Text::create() ... .draw(ctx)."""
    # Text(...) with a first string argument.
    source = re.sub(r"new Text\(\s*([\"'])(.*?)\1",
                    r'mtr::Text::create().text("\2"', source)
    source = re.sub(r"new Text\(\s*([A-Za-z_$][\w$.]*\(\))\s*\)",
                    r"mtr::Text::create().text(\1.data, \1.len) /* TODO: verify StrView */", source)
    source = re.sub(r"new Text\(\s*([A-Za-z_$][\w$.]*)\s*\)",
                    r"mtr::Text::create().text(\1) /* TODO: JS value - pass a const char* or (data, len) */", source)
    for js, cpp in TEXT_CHAIN:
        source = re.sub(r"\." + js + r"\(", "." + cpp + "(", source)
    # .draw() with no argument -> .draw(ctx) (the context is an argument
    # in C++, not a closure variable).
    source = re.sub(r"\.draw\(\s*\)", ".draw(ctx)", source)
    return source


def convert_let(source: str) -> str:
    """var/let/const -> auto (with a TODO for genuinely polymorphic vars)."""
    return re.sub(r"\b(?:var|let|const)\s+", "auto ", source)


def convert_props(source: str) -> str:
    for pattern, replacement in PROP_TO_METHOD:
        source = re.sub(pattern, replacement, source)
    return source


def convert_helpers(source: str) -> str:
    for pattern, replacement in HELPER_REWRITES:
        source = re.sub(pattern, replacement, source)
    return source


def extract_state_hints(source: str) -> list:
    """Variables assigned OUTSIDE create/render (module scope in JS) go to
    the State struct — collect them as TODO hints."""
    hints = []
    for match in STATE_HINT.finditer(source):
        name, value = match.group(1), match.group(2).strip()
        if re.match(r"^-?\d+(\.\d+)?$", value) or value in ("true", "false") \
                or value.startswith('"') or value.startswith("'"):
            hints.append((name, value))
    return hints


def guess_type(value: str) -> str:
    if re.match(r"^-?\d+$", value):
        return "long"
    if re.match(r"^-?\d*\.\d+$", value):
        return "double"
    if value in ("true", "false"):
        return "bool"
    if value.startswith('"') or value.startswith("'"):
        return "const char*"
    return "/* TODO type */ double"


def guess_init(value: str) -> str:
    if value in ("true", "false"):
        return value
    if value.startswith('"') or value.startswith("'"):
        return value
    if re.match(r"^-?\d+(\.\d+)?$", value):
        return value
    return "0 /* was: " + value.replace("*/", "") + " */"


def extract_function_bodies(source: str) -> dict:
    """Pull the {create,render,dispose}(ctx, state, ...) bodies out of the
    JS source (brace-matched), so the generated C++ only embeds code that
    belongs inside the lifecycle methods."""
    bodies = {}
    for name in ("create", "render", "dispose"):
        match = re.search(r"function\s+" + name + r"\s*\([^)]*\)\s*\{", source)
        if match is None:
            continue
        depth = 0
        start = match.end() - 1
        for i in range(start, len(source)):
            if source[i] == '{':
                depth += 1
            elif source[i] == '}':
                depth -= 1
                if depth == 0:
                    bodies[name] = source[start + 1:i]
                    break
    return bodies


def convert(source: str, script_id: str, kind: str) -> str:
    bodies = extract_function_bodies(source)
    converted_bodies = {}
    for name, body in bodies.items():
        body = convert_forEach(body)
        body = convert_text_chains(body)
        body = convert_props(body)
        body = convert_helpers(body)
        body = convert_let(body)
        body = re.sub(r"\breturn\b", "/* return */", body)  # JS early-returns need re-shaping
        converted_bodies[name] = body

    state_hints = extract_state_hints(source)

    state_fields = "\n".join(
        f"    {guess_type(value)} {name} = {guess_init(value)};  // was module-scope in the JS source"
        for name, value in state_hints) or "    /* TODO: move the JS closure state here. */"
    # Bodies reference the state through state.<name>.
    for name, _ in state_hints:
        for key in list(converted_bodies):
            converted_bodies[key] = re.sub(r"\b" + re.escape(name) + r"\b",
                                           "state." + name, converted_bodies[key])

    wrapper_type = {"pids": "Pids", "vehicle": "Vehicle"}.get(kind, "Pids")
    script_base = {"pids": "PidsScript", "vehicle": "VehicleScript"}.get(kind, "PidsScript")
    context_type = {"pids": "PidsContext", "vehicle": "VehicleContext"}.get(kind, "PidsContext")

    create_body = converted_bodies.get("create", "        /* TODO: no JS create() found - port resource acquisition. */")
    render_body = converted_bodies.get("render", "        /* TODO: no JS render() found. */")
    dispose_body = converted_bodies.get("dispose", "        /* TODO: no JS dispose() found. */")

    return f"""{HEADER}
/* TODO: script id "{script_id}" - must match the mtr_custom_resources.json
   entry this module is declared under. */
struct ConvertedState {{
{state_fields}
}};

struct ConvertedScript : mtr::{script_base}<ConvertedState> {{
    static constexpr auto ID = "{script_id}";

    void create(mtr::{context_type}& ctx, ConvertedState& state, const mtr::{wrapper_type}& wrapper) override {{
        (void)ctx; (void)state; (void)wrapper;
        auto& pids = wrapper; (void)pids;
        auto& vehicle = wrapper; (void)vehicle;
{create_body}
    }}

    void render(mtr::{context_type}& ctx, ConvertedState& state, const mtr::{wrapper_type}& wrapper) override {{
        (void)state;
        auto& pids = wrapper; (void)pids;
        auto& vehicle = wrapper; (void)vehicle;
{render_body}
    }}

    void dispose(mtr::{context_type}& ctx, ConvertedState& state, const mtr::{wrapper_type}& wrapper) override {{
        (void)ctx; (void)state; (void)wrapper;
{dispose_body}
    }}
}};

MTR_REGISTER_{script_base.replace("Script", "").upper()}_SCRIPT(ConvertedScript)
"""


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__,
                                     formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("input", help="the JavaScript source file")
    parser.add_argument("-o", "--output", help="write here instead of stdout")
    parser.add_argument("--id", default="mypack:converted", help="script id for the module")
    parser.add_argument("--kind", default="pids", choices=["pids", "vehicle"],
                        help="script kind (wrapper shape)")
    args = parser.parse_args()

    with open(args.input, encoding="utf-8") as handle:
        source = handle.read()
    converted = convert(source, args.id, args.kind)
    if args.output:
        with open(args.output, "w", encoding="utf-8") as handle:
            handle.write(converted)
        print(f"wrote {args.output} — review the TODO markers", file=sys.stderr)
    else:
        sys.stdout.write(converted)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
